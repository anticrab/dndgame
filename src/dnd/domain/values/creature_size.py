"""Размер существа.

Книга 2024 (стр. 24, «Размер существа»). Размер определяет:

* сколько клеток занимает существо на боевой карте;
* через какие клетки оно может проходить (только существа меньшего/
  большего размера на 2 категории);
* грузоподъёмность (умножается на множитель размера);
* кого можно поднять/тащить.

В MVP все существа `MEDIUM` (1×1 клетка). Enum заложен заранее по
решению Q35 — чтобы `Battlefield` и правила досягаемости не
переписывались при добавлении больших существ пост-MVP.
"""

from __future__ import annotations

from enum import StrEnum


class CreatureSize(StrEnum):
    """Шесть размеров из книги 2024."""

    TINY = "tiny"  # 2.5×2.5 фт — феечки, крысы; в MVP не используем
    SMALL = "small"  # 5×5 фт — гномы, полурослики, гоблины (1 клетка)
    MEDIUM = "medium"  # 5×5 фт — люди, эльфы, орки (1 клетка)
    LARGE = "large"  # 10×10 фт (2×2 клетки) — медведь, огр; пост-MVP
    HUGE = "huge"  # 15×15 фт (3×3 клетки) — гигант
    GARGANTUAN = "gargantuan"  # 20×20 фт+ (4×4 и больше) — драконы

    @property
    def squares_side(self) -> int:
        """Сторона занимаемой области в клетках.

        TINY и SMALL/MEDIUM формально занимают 1 клетку (TINY — четверть,
        но в нашей сетке это всё равно одна позиция; до 4 TINY могут
        находиться в одной клетке).
        """
        return {
            CreatureSize.TINY: 1,
            CreatureSize.SMALL: 1,
            CreatureSize.MEDIUM: 1,
            CreatureSize.LARGE: 2,
            CreatureSize.HUGE: 3,
            CreatureSize.GARGANTUAN: 4,
        }[self]
