"""Порт генератора случайных чисел.

Весь домен бросает кости только через этот интерфейс. Это даёт:

* детерминированные тесты (seeded RNG / scripted RNG);
* возможность отделить «реальный случай» от «крита по сценарию мастера».
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable


@runtime_checkable
class RNG(Protocol):
    """Минимальный контракт ГПСЧ.

    Реализации должны обеспечивать равномерное распределение в полуинтервале
    ``[1, sides]`` для ``roll``. Дополнительные методы — для случаев, когда
    нужен не куб, а вероятность или выбор из коллекции.
    """

    def roll(self, sides: int) -> int:
        """Бросить один кубик с ``sides`` гранями (k4, k6, k8, k10, k12, k20, k100)."""

    def random(self) -> float:
        """Равномерное число из ``[0.0, 1.0)``."""
