"""Порт ``EventBus`` — синхронная FIFO publish/subscribe.

Контракт зафиксирован в ``docs/ENGINE.md`` §5.2. Главные пункты,
которые **должна** соблюдать любая реализация:

1. **FIFO порядок.** Все события обрабатываются в порядке `publish()`.
   Если подписчик внутри своего хендлера публикует новое событие,
   оно ставится **в хвост** текущей очереди — не вызывается рекурсивно.
2. **Изменения подписок во время диспетчеризации.** ``subscribe`` /
   возврат ``Unsubscribe`` во время дисптатча применяются **со следующей**
   публикации, не задним числом.
3. **Изоляция исключений.** Если подписчик кинул исключение, оно
   ловится, логируется как ERROR через ``logging``, остальные
   подписчики получают событие штатно. ``publish()`` снаружи ничего
   не raise.
4. **Подписчик не получает свои же события.** Подписка идёт по типу
   события; ``publish(e)`` внутри хендлера на событие другого типа не
   доставит ``e`` обратно тому же хендлеру, если он подписан только
   на свой тип.

Реализация — ``infrastructure.events.in_memory_event_bus.InMemoryEventBus``.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Protocol, TypeVar

from dnd.application.dto.engine_event import EngineEvent

E = TypeVar("E", bound=EngineEvent)

# Возвращаемое значение `subscribe` — токен отписки. Это просто
# zero-arg callable, который снимает подписку при вызове. Реализация
# хранит мапу подписчиков и удаляет нужный по этому токену.
Unsubscribe = Callable[[], None]

# Хендлер — функция, принимающая событие конкретного типа и ничего не
# возвращающая. На самом деле может побочно вызвать `publish` — тогда
# применяется правило 1 (отложенная доставка).
EventHandler = Callable[[E], None]


class EventBus(Protocol):
    """Шина событий движка."""

    def publish(self, event: EngineEvent) -> None:
        """Опубликовать событие.

        Реализация обязана соблюдать пункты 1–4 контракта выше.
        Возвращает после того, как обработаны все события **текущей
        волны** (т.е. опубликованные и через вложенные `publish` тоже).
        """

    def subscribe(
        self,
        event_type: type[E],
        handler: EventHandler[E],
    ) -> Unsubscribe:
        """Подписаться на события конкретного типа (включая подклассы).

        Возвращает токен — вызов токена снимает эту подписку. Подписки
        вызываются в порядке регистрации (FIFO для одного типа).
        """
